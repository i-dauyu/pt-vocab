// 音声にするときの読み方（略語はアルファベットで読ませる）
const PT_SPOKEN_RULES = [
  [/\/a\b/g, ''],
  [/\bSNS\b/g, 'ésse ene ésse'],
  [/\bIRS\b/g, 'i érre ésse'],
  [/\bPSP\b/g, 'pê ésse pê'],
  [/\bGNR\b/g, 'gê ene érre'],
  [/\bCTT\b/g, 'cê tê tê'],
  [/\bMB WAY\b/g, 'eme bê uei'],
  [/\bT2\b/g, 'tê dois'],
  [/\bNISS\b/g, 'nisse'],
  [/\b112\b/g, 'cento e doze'],
];

window.ptSpoken = (text) => PT_SPOKEN_RULES.reduce((s, [from, to]) => s.replace(from, to), text);

// 読み上げる文からファイル名を作る（FNV-1a）。文を直すと音声も作り直される
window.ptAudioId = (text) => {
  let h = 0x811c9dc5;
  for (const ch of window.ptSpoken(text)) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
};
